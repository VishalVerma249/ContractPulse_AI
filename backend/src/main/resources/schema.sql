CREATE TABLE projects (
    id VARCHAR(40) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    agency VARCHAR(120) NOT NULL,
    contractor VARCHAR(120) NOT NULL,
    budget_crores DECIMAL(12, 2) NOT NULL,
    baseline_finish_date DATE NOT NULL,
    forecast_finish_date DATE NOT NULL,
    delay_risk INTEGER,
    cost_risk INTEGER,
    status VARCHAR(40) NOT NULL,
    color VARCHAR(20) NOT NULL,
    initials VARCHAR(8) NOT NULL
);

CREATE TABLE milestones (
    id VARCHAR(60) PRIMARY KEY,
    project_id VARCHAR(40) NOT NULL,
    name VARCHAR(120) NOT NULL,
    planned_finish_date DATE NOT NULL,
    forecast_finish_date DATE,
    actual_finish_date DATE,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT fk_milestones_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE progress_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(40) NOT NULL,
    snapshot_date DATE NOT NULL,
    planned_progress INTEGER NOT NULL,
    actual_progress INTEGER NOT NULL,
    CONSTRAINT uq_progress_project_date UNIQUE (project_id, snapshot_date),
    CONSTRAINT fk_progress_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
    CONSTRAINT ck_planned_progress CHECK (planned_progress BETWEEN 0 AND 100),
    CONSTRAINT ck_actual_progress CHECK (actual_progress BETWEEN 0 AND 100)
);
